import { chromium } from '@playwright/test';
const [out] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => sessionStorage.setItem('hypsos-intro-seen', '1'));
const page = await ctx.newPage();
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.waitForTimeout(4500);
const cta = page.getByRole('link', { name: 'Comprar Chapter 01' });
const box = await cta.boundingBox();
await page.mouse.move(box.x - 40, box.y - 40);
await page.mouse.move(box.x + box.width * 0.85, box.y + box.height * 0.8, { steps: 12 });
await page.waitForTimeout(500);
console.log('cta transform', await cta.evaluate((el) => getComputedStyle(el).transform));
await page.screenshot({ path: out, clip: { x: box.x - 120, y: box.y - 120, width: box.width + 240, height: box.height + 200 } });
await browser.close();
