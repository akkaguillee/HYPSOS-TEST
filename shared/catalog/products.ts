/**
 * Genera el stock inicial de ejemplo de todas las variantes (siembra la base de datos).
 * `overrides` permite fijar variantes agotadas o con pocas unidades.
 */
function stock(
  colorList: ColorOption[],
  sizes: string[],
  base: number,
  overrides: Record<string, number> = {},
): Record<string, number> {
  const inventory: Record<string, number> = {};
  for (const color of colorList) {
    for (const size of sizes) {
      const key = `${color.id}:${size}`;
      inventory[key] = overrides[key] ?? base;
    }
  }
  return inventory;
}

